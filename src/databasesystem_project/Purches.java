    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String foodName = jComboBox1.getSelectedItem().toString();
        String productName = jComboBox2.getSelectedItem().toString();

        boolean foodChosen = !foodName.equals("-- Select Food --");
        boolean productChosen = !productName.equals("-- Select Product --");

        int foodQty = (int) jSpinner2.getValue();   // ✅ Food spinner
        int productQty = (int) jSpinner1.getValue(); // ✅ Product spinner

        if (!foodChosen && !productChosen) {
            JOptionPane.showMessageDialog(this, "Select Food or Product (or both).");
            return;
        }

        if (foodChosen && foodQty <= 0) {
            JOptionPane.showMessageDialog(this, "Food quantity must be greater than 0.");
            return;
        }

        if (productChosen && productQty <= 0) {
            JOptionPane.showMessageDialog(this, "Product quantity must be greater than 0.");
            return;
        }

        try (Connection con = DBConnection.getConnection()) {

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

            // =========================
            // 🍝 FOOD PRODUCT
            if (foodChosen) {

                String supplierName = "";
                double foodPrice = 0;

                PreparedStatement pstFood = con.prepareStatement(
                        "SELECT s.supplier_name, f.cost_price "
                        + "FROM FoodProduct f "
                        + "JOIN Supplier s ON f.supplier_id = s.supplier_id "
                        + "WHERE f.ingredients = ?"
                );

                pstFood.setString(1, foodName);

                ResultSet rsFood = pstFood.executeQuery();
                if (rsFood.next()) {
                    supplierName = rsFood.getString("supplier_name");
                    foodPrice = rsFood.getDouble("cost_price"); // ✅ الآن صحيح
                }

                rsFood.close();
                pstFood.close();

                model.addRow(new Object[]{
                    foodName,
                    supplierName,
                    foodQty,
                    foodPrice,
                    foodQty * foodPrice
                });
            }

            // =========================
            // 🥤 NORMAL PRODUCT
            // =========================
            if (productChosen) {

                int productId = 0;
                double unitPrice = 0;
                String supplierName = "";

                PreparedStatement pst = con.prepareStatement(
                        "SELECT p.product_id, p.cost_price, s.supplier_name "
                        + "FROM Product p "
                        + "JOIN Supplier s ON p.supplier_id = s.supplier_id "
                        + "WHERE p.product_name = ?"
                );
                pst.setString(1, productName);

                ResultSet rs = pst.executeQuery();
                if (rs.next()) {
                    productId = rs.getInt("product_id");
                    unitPrice = rs.getDouble("cost_price");
                    supplierName = rs.getString("supplier_name");
                }

                rs.close();
                pst.close();

                model.addRow(new Object[]{
                    productName,
                    supplierName,
                    productQty,
                    unitPrice,
                    productQty * unitPrice
                });
            }

            // 🔄 reset spinners
            jSpinner1.setValue(0);
            jSpinner2.setValue(0);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
// 🔄 Reset ComboBoxes to first option
        jComboBox1.setSelectedIndex(0); // -- Select Food --
        jComboBox2.setSelectedIndex(0); // -- Select Product --

// 🔄 Reset Spinners
        jSpinner1.setValue(0); // Product quantity
        jSpinner2.setValue(0); // Food quantity


    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
           DefaultTableModel model = (DefaultTableModel) jTable1.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "No items to complete order.");
            return;
        }

        try (Connection con = DBConnection.getConnection()) {

            con.setAutoCommit(false);

            // 1) INSERT INTO PurchaseOrder
            PreparedStatement pstOrder = con.prepareStatement(
                    "INSERT INTO PurchaseOrder (order_date, status, created_by) "
                    + "VALUES (GETDATE(), 'Completed', ?)",
                    Statement.RETURN_GENERATED_KEYS
            );

            pstOrder.setInt(1, loggedEmployedId);
            pstOrder.executeUpdate();

            ResultSet rsKey = pstOrder.getGeneratedKeys();
            int orderId = 0;
            if (rsKey.next()) {
                orderId = rsKey.getInt(1);
            }
            rsKey.close();
            pstOrder.close();

            if (orderId == 0) {
                con.rollback();
                JOptionPane.showMessageDialog(this, "Failed to create order!");
                return;
            }

            // 2) INSERT ITEMS
            PreparedStatement pstItem = con.prepareStatement(
                    "INSERT INTO PurchaseOrderItems "
                    + "(order_id, product_id, FoodProduct_id, supplier_id, quantity, unit_price) "
                    + "VALUES (?, ?, ?, ?, ?, ?)"
            );

            for (int i = 0; i < model.getRowCount(); i++) {

                String itemName = model.getValueAt(i, 0).toString();
                String supplierName = model.getValueAt(i, 1).toString();
                int quantity = Integer.parseInt(model.getValueAt(i, 2).toString());
                double unitPrice = Double.parseDouble(model.getValueAt(i, 3).toString());

                Integer productId = getProductIdByName(con, itemName);              // returns null if not found
                Integer foodId = getFoodProductIdByIngredient(con, itemName);       // returns null if not found
                int supplierId = getSupplierIdByName(con, supplierName);

                pstItem.setInt(1, orderId);

                // ✅ لازم واحد منهم فقط (Product أو FoodProduct)
                if (productId != null) {
                    pstItem.setInt(2, productId);
                    pstItem.setNull(3, java.sql.Types.INTEGER);
                } else if (foodId != null) {
                    pstItem.setNull(2, java.sql.Types.INTEGER);
                    pstItem.setInt(3, foodId);
                } else {
                    // لا موجود في Product ولا في FoodProduct
                    con.rollback();
                    JOptionPane.showMessageDialog(this, "Item not found in DB: " + itemName);
                    return;
                }

                pstItem.setInt(4, supplierId);
                pstItem.setInt(5, quantity);
                pstItem.setDouble(6, unitPrice);

                pstItem.addBatch();
            }

            pstItem.executeBatch();
            pstItem.close();

            con.commit();

            JOptionPane.showMessageDialog(
                    this,
                    "Order completed successfully!\nOrder ID: " + orderId
            );

            // Return to Menu
            Menu menu = new Menu(user_name);
            this.dispose();
            menu.setVisible(true);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            e.printStackTrace();
        }

    }//GEN-LAST:event_jButton1ActionPerformed
    private Integer getProductIdByName(Connection con, String productName) throws Exception {

        PreparedStatement pst = con.prepareStatement(
                "SELECT product_id FROM Product WHERE product_name = ?"
        );
        pst.setString(1, productName);

        ResultSet rs = pst.executeQuery();

        Integer id = null;
        if (rs.next()) {
            id = rs.getInt("product_id");
        }

        rs.close();
        pst.close();

        return id;  // null if not found
    }

