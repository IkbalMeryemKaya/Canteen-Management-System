     private int getSupplierIdByName(Connection con, String supplierName) throws Exception {

        int supplierId = 0;

        PreparedStatement pst = con.prepareStatement(
                "SELECT supplier_id FROM Supplier WHERE supplier_name = ?"
        );
        pst.setString(1, supplierName);

        ResultSet rs = pst.executeQuery();
        if (rs.next()) {
            supplierId = rs.getInt("supplier_id");
        }

        rs.close();
        pst.close();

        return supplierId;
    }

   private Integer getFoodProductIdByIngredient(Connection con, String ingredient) throws Exception {
        PreparedStatement pst = con.prepareStatement(
                "SELECT FoodProduct_id FROM FoodProduct WHERE ingredients = ?"
        );
        pst.setString(1, ingredient);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            return rs.getInt("FoodProduct_id");
        }
        return null;
    }
