    private void bttn_remove_empActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttn_remove_empActionPerformed
        // TODO add your handling code here:
        String selected_emp = list_of_employee.getSelectedValue();
        if (selected_emp == null) {
            JOptionPane.showMessageDialog(this, "Please select an employee!");
            return;
        }

        try {
            Connection conn = DBConnection.getConnection();
            if (conn != null) {
                String sql = "DELETE FROM Employee WHERE emp_name = ? AND role = 'Employee'";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, selected_emp);

                int rows = pst.executeUpdate();

                if (rows > 0) {
                    JOptionPane.showMessageDialog(this, "Employee removed successfully!");

                    // Listeden silinen ismi çıkar
                    loadEmployeeList();  // listeyi yenile
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to remove employee!");
                }

                pst.close();
                conn.close();
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage() + "\n" + selected_emp);
            e.printStackTrace();
        }

    }//GEN-LAST:event_bttn_remove_empActionPerformed


