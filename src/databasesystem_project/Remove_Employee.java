    private void loadEmployeeList() {
        DefaultListModel<String> list_model = new DefaultListModel<>();

        try {
            Connection con = DBConnection.getConnection();

            String sql = "SELECT emp_name FROM Employee WHERE role = 'Employee'";

            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                String name = rs.getString("emp_name");
                list_model.addElement(name);
            }

            rs.close();
            pst.close();
            con.close();

        } catch (Exception e) {
            System.out.println("Hata (loadStockTable): " + e.getMessage());
        }

        list_of_employee.setModel(list_model);
    }

