    private void bttn_completeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bttn_completeActionPerformed
        // TODO add your handling code here:
        if (!rbttn_cash.isSelected() && !rbttn_credit_card.isSelected()) {
            JOptionPane.showMessageDialog(this, "Please choose a payment type!");
            return;
        }

        LocalDate date = LocalDate.now();
        Date today = Date.valueOf(date);
        int type = rbttn_cash.isSelected() ? 1 : 2;
        float total_price = disc_total;
        System.out.println("******** in complete button, total_price: " +total_price+ " *******");

        try {
            Connection conn = DBConnection.getConnection();
            if (conn != null) {
                String sql = "INSERT INTO Sales (sale_date, total_amount, payment_id) VALUES (?,?,?)";
                PreparedStatement pst = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
                pst.setDate(1, today);
                pst.setFloat(2, total_price);
                pst.setInt(3, type);

                pst.executeUpdate();

                int salesId = -1;
                ResultSet rs = pst.getGeneratedKeys();
                if (rs.next()) {
                    salesId = rs.getInt(1);
                }

                addSalesItems(model, salesId);
                JOptionPane.showMessageDialog(this, "Shopping completed succesfully!!");

                rs.close();
                pst.close();
                conn.close();
                model.setRowCount(0);
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        }

    }//GEN-LAST:event_bttn_completeActionPerformed

