    private void txt_discountKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_discountKeyReleased
        // TODO add your handling code here:
        String discount_code = txt_discount.getText();

        String sql = "SELECT discount_rate, start_date, end_date FROM Discount WHERE code = ?";
        try (Connection conn = DBConnection.getConnection(); PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, discount_code);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                LocalDate today = LocalDate.now();
                LocalDate start_date = rs.getDate("start_date").toLocalDate();
                LocalDate end_date = rs.getDate("end_date").toLocalDate();
                float discount_rate = rs.getFloat("discount_rate");
                lbl_valid_invalid.setText("");

                if (today.isAfter(start_date) && today.isBefore(end_date)) {
                    lbl_total.setFont(new Font("Imprint MT Shadow", Font.ITALIC, 12));
                    lbl_total.setForeground(new Color(0, 0, 0, 128));
                    disc_total = total - (total / 100 * discount_rate);
                    lbl_total_for_discount.setText(String.valueOf(disc_total));
                } else {
                    lbl_valid_invalid.setText("Historical Past Code!");
                }
            } else {
                lbl_valid_invalid.setText("Invalid code!");
                lbl_total_for_discount.setText("");
                lbl_total.setText(String.valueOf(total));
                lbl_total.setFont(new Font("Imprint MT Shadow", Font.BOLD, 18));
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_txt_discountKeyReleased

