    public int getProductId(String productName) {
        int id = -1;

        String sql = "SELECT product_id FROM Product WHERE product_name = ?";
        try (Connection conn = DBConnection.getConnection(); PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setString(1, productName);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                id = rs.getInt("product_id");
            }
        } catch (Exception e) {
            e.printStackTrace();
        }

        System.out.println("Product id bulundu:" + id);
        return id;
    }

    private void stockReduction(int product_id, int count) {
        try {
            Connection conn = DBConnection.getConnection();
            if (conn != null) {
                String sql = "UPDATE Stock SET quantity = quantity - ? WHERE product_id = ?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setInt(1, count);
                pst.setInt(2, product_id);

                pst.executeUpdate();

                pst.close();
                conn.close();
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        }
    }

    private void addSalesItems(DefaultTableModel model, int salesId) {
        String sql = "INSERT INTO SalesItems (sales_id, product_id, quantity, unit_price) VALUES (?,?,?,?)";

        try {
            Connection conn = DBConnection.getConnection();
            if (conn != null) {

                PreparedStatement pst = conn.prepareStatement(sql);
                for (int i = 0; i < model.getRowCount(); i++) {
                    String product_name = model.getValueAt(i, 0).toString();
                    int quantity = Integer.parseInt(model.getValueAt(i, 1).toString());
                    float unit_price = Float.parseFloat(model.getValueAt(i, 2).toString());
                    pst.setInt(1, salesId);
                    pst.setInt(2, getProductId(product_name));
                    pst.setFloat(3, quantity);
                    pst.setFloat(4, unit_price);

                    pst.executeUpdate();
                    stockReduction(getProductId(product_name), quantity);
                }

                JOptionPane.showMessageDialog(this, "Shopping completed succesfully!!");
                pst.close();
                conn.close();
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Database error: " + ex.getMessage());
        }
    }

